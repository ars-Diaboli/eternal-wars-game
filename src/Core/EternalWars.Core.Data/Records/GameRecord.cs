    /// <summary>Map JSON settings plus the command hierarchy (kept out of Domain) and compact ids.</summary>
    internal static readonly JsonSerializerOptions Options = CreateOptions();

    /// <summary>
    /// The record's JSON settings (commands, maps, compact ids), with <paramref name="modifier"/> for one more type hierarchy: the LAN messages
    /// carry commands and records (ADR-192).
    /// </summary>
    public static JsonSerializerOptions CreateOptions(Action<JsonTypeInfo>? modifier = null)
    {
        var resolver = new DefaultJsonTypeInfoResolver { Modifiers = { AddCommandTypes, Maps.MapConverter.AddObjectTypes, Maps.MapEventJson.AddTypes } };
        if (modifier is not null)
        {
            resolver.Modifiers.Add(modifier);
        }

        return new(JsonDefaults.Options)
        {
            TypeInfoResolver = resolver,
            Converters = { new IdConverter<PlayerId>(v => new(v), id => id.Value), new IdConverter<HeroId>(v => new(v), id => id.Value),
                new IdConverter<MapObjectId>(v => new(v), id => id.Value) },
        };
    }

    public static string Serialize(GameRecordDocument record) => JsonSerializer.Serialize(record, Options);

    /// <summary>
    /// Reads a replay or a save; its map, when older, is upgraded to the current format first (<see cref="MapMigrations"/>, ADR-174), and so are
    /// the options of a record before <see cref="GameRecordDocument.DifficultyVersion"/>.
    /// </summary>
    public static GameRecordDocument Deserialize(string json) =>
        (Upgrade(json) is { } upgraded
            ? upgraded.Deserialize<GameRecordDocument>(Options)
            : JsonSerializer.Deserialize<GameRecordDocument>(json, Options))
        ?? throw new FormatException("Replay file is empty.");

    /// <summary>The record's JSON upgraded to the current format; null when it needs nothing (it is then read as it is).</summary>
    private static JsonNode? Upgrade(string json)
    {
        var upgraded = MapMigrations.Upgrade(json, "map");
        if (VersionOf(json) is not { } version || version >= GameRecordDocument.DifficultyVersion)
        {
            return upgraded;
        }

        var root = upgraded ?? JsonNode.Parse(json, new JsonNodeOptions { PropertyNameCaseInsensitive = true });
        if (root is JsonObject record && record["options"] is JsonObject options && options["complexity"] is { } complexity)
        {
            options.Remove("complexity");
            options["difficulty"] = complexity;
            DifficultyNames.Upgrade(options, "difficulty");
        }

        return root;
    }

    /// <summary>The record's top-level <c>formatVersion</c> (1 when it names none), read without parsing the rest; null when the text is no record.</summary>
    private static int? VersionOf(string json)
    {
        try
        {
            var reader = new Utf8JsonReader(System.Text.Encoding.UTF8.GetBytes(json));
            if (!reader.Read() || reader.TokenType != JsonTokenType.StartObject)
            {
                return null;
            }

            while (reader.Read() && reader.TokenType == JsonTokenType.PropertyName)
            {
                var isVersion = string.Equals(reader.GetString(), "formatVersion", StringComparison.OrdinalIgnoreCase);
                reader.Read();
                if (isVersion)
                {
                    return reader.TokenType == JsonTokenType.Number && reader.TryGetInt32(out var version) ? version : null;
                }

                reader.Skip();
            }

            return 1;
        }
        catch (JsonException)
        {
            return null;
        }
    }

    /// <summary>Writes the record to a file (replacing it) as it serializes, without the whole text in memory first (<see cref="Write"/>).</summary>
    public static void Save(GameRecordDocument record, string path)
    {
        // Written beside the target and moved over it, so a save that fails part way leaves the file at the path as it was.
        var temp = path + ".part";
        try
        {
            using (var stream = new FileStream(temp, FileMode.Create, FileAccess.Write, FileShare.None))
            {
                Write(record, stream);
            }

            File.Move(temp, path, overwrite: true);
        }
        catch
        {
            File.Delete(temp);
            throw;
        }
    }

    /// <summary>Writes the record to <paramref name="stream"/> as UTF-8 JSON as it serializes: the bytes of <see cref="Serialize"/>'s text, without a byte order mark.</summary>
    public static void Write(GameRecordDocument record, Stream stream) => JsonSerializer.Serialize(stream, record, Options);

    public static GameRecordDocument Load(string path) => Deserialize(File.ReadAllText(path));

    private static void AddCommandTypes(JsonTypeInfo info)
    {
        if (info.Type != typeof(GameCommand))
        {
            return;
        }

        info.PolymorphismOptions = new JsonPolymorphismOptions
        {
            TypeDiscriminatorPropertyName = "type",
            UnknownDerivedTypeHandling = JsonUnknownDerivedTypeHandling.FailSerialization,
        };
        foreach (var (type, name) in CommandTypes)
        {
            info.PolymorphismOptions.DerivedTypes.Add(new JsonDerivedType(type, name));
        }
    }

    /// <summary>Writes strongly typed ids as plain numbers.</summary>
    private sealed class IdConverter<T>(Func<int, T> create, Func<T, int> value) : JsonConverter<T>
    {
        public override T Read(ref Utf8JsonReader reader, Type typeToConvert, JsonSerializerOptions options) => create(reader.GetInt32());

        public override void Write(Utf8JsonWriter writer, T id, JsonSerializerOptions options) => writer.WriteNumberValue(value(id));
    }
