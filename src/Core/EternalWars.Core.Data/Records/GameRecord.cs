/// <summary>
/// A replayable game (<c>*.ewreplay.json</c>) or a saved game (<c>*.ewsave.json</c>, ADR-058): the map as it was at the
/// start, the game options (incl. the seed) and every accepted command. <see cref="FinalDigest"/> lets a replay prove it
/// reached the same state. Version 2 adds <see cref="Save"/>, version 3 <see cref="Generated"/>; older files still load.
/// </summary>
public sealed record GameRecordDocument
{
    public const int CurrentFormatVersion = 3;

    public int FormatVersion { get; init; } = CurrentFormatVersion;

    public required MapDocument Map { get; init; }

    public required GameOptions Options { get; init; }

    public required IReadOnlyList<GameCommand> Commands { get; init; }

    /// <summary><see cref="GameStateDigest"/> after the last command, if recorded.</summary>
    public string? FinalDigest { get; init; }

    /// <summary>What the save menu shows; present in saved games.</summary>
    public SaveInfo? Save { get; init; }

    /// <summary>How the map was generated, for a game on a random map (RMG-5); null for a hand-made map.</summary>
    public GenerationInfo? Generated { get; init; }
}

/// <summary>
/// The inputs of a generated map (the map itself is in <see cref="GameRecordDocument.Map"/>): template, size, seed, the attempt the generator kept
/// and the generator version (<see cref="MapGenerator.Version"/>), shown with the seed so a seed shared with another version can be warned about.
/// </summary>
public sealed record GenerationInfo(string Template, int Size, ulong Seed, int Attempt, int GeneratorVersion)
{
    /// <summary>This version of the game's generator.</summary>
    public static GenerationInfo Of(string template, int size, ulong seed, int attempt) => new(template, size, seed, attempt, MapGenerator.Version);

    /// <summary>A warning when the seed would give another map with this game's generator; null when it gives the same one.</summary>
    public string? VersionWarning => GeneratorVersion == MapGenerator.Version
        ? null
        : $"This map was generated by generator version {GeneratorVersion}; this game has version {MapGenerator.Version}, so the same seed may give another map.";
}

/// <summary>The label of a saved game: enough to pick it from a list without replaying it.</summary>
/// <param name="Name">The name the player gave the save.</param>
/// <param name="SavedAt">UTC time of saving, ISO 8601.</param>
/// <param name="Date">The game's calendar date.</param>
/// <param name="Player">Whose turn it was.</param>
/// <param name="InBattle">Saved in the middle of a battle.</param>
/// <param name="Map">Name of the map.</param>
public sealed record SaveInfo(string Name, string SavedAt, string Date, string Player, bool InBattle, string Map);

/// <summary>Records and replays games from their command logs (ADR-036).</summary>
public static class GameReplay
{
    /// <summary>
    /// Captures a finished or ongoing session. <paramref name="initialMap"/> must be the map document the
    /// session was created from (save it before starting: the live state has changed since).
    /// </summary>
    public static GameRecordDocument Record(MapDocument initialMap, GameSession session, string? saveName = null, GenerationInfo? generated = null) => new()
    {
        Map = initialMap,
        Generated = generated,
        Options = session.State.Options,
        Commands = session.CommandLog.ToList(),
        FinalDigest = GameStateDigest.Compute(session.State),
        Save = saveName is null
            ? null
            : new SaveInfo(
                saveName,
                DateTimeOffset.UtcNow.ToString("O", CultureInfo.InvariantCulture),
                session.State.Date.ToString(),
                session.State.CurrentPlayer.Name,
                session.State.Battle is not null,
                initialMap.Name),
    };

    /// <summary>
    /// Rebuilds the game from the record: same map, options and commands. Throws <see cref="InvalidOperationException"/>
    /// if a command is refused or the final digest differs (the game is not deterministic, or content changed).
    /// </summary>
    public static GameSession Replay(
        GameRecordDocument record,
        MapObjectCatalog? catalog = null,
        CreatureCatalog? creatures = null,
        HeroCatalog? heroRoster = null,
        BuildingCatalog? buildings = null,
        TerrainCatalog? terrains = null,
        ArtifactCatalog? artifacts = null)
    {
        var session = new GameSession(MapConverter.ToGameState(record.Map, catalog, record.Options, terrains, creatures, heroRoster, buildings, artifacts));
        session.Start();
        for (var i = 0; i < record.Commands.Count; i++)
        {
            var result = session.Execute(record.Commands[i]);
            if (!result.IsAccepted)
            {
                throw new InvalidOperationException($"Replay diverged at command {i} ({record.Commands[i]}): {result.Error}");
            }
        }

        if (record.FinalDigest is { } expected && GameStateDigest.Compute(session.State) is var actual && actual != expected)
        {
            throw new InvalidOperationException($"Replay ended in state {actual}, the record says {expected}.");
        }

        return session;
    }
}

