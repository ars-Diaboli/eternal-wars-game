using System.Globalization;
using System.Text.RegularExpressions;
using EternalWars.Core.Domain.Analysis;
using EternalWars.Core.Domain.Game;

namespace EternalWars.Core.Generation;

/// <summary>How a generated map was made, as its description records it (<see cref="EditorMapGenerator.Describe"/>).</summary>
public sealed record GeneratedDescription(string Template, int Size, ulong Seed, int Attempt, int Version);

/// <summary>The zones a map's description gives (null: none), and a note saying where they come from or why there are none.</summary>
public sealed record ZoneReading(ZoneMap? Zones, string Note);

/// <summary>
/// The zones of a generated map for the editor's zones overlay (ADR-264): the description names the template, size, seed and attempt, and the
/// layout stage (<see cref="ZoneLayouter"/>) run again on them gives each tile's zone, as the generator laid them. Only the layout runs, so
/// it is quick; a map whose size changed since, or whose template is not found, has none.
/// </summary>
public static partial class GeneratedZones
{
    /// <summary>Reads how a map was generated from its description; null when the description does not start as a generated map's does.</summary>
    public static GeneratedDescription? Parse(string description)
    {
        ArgumentNullException.ThrowIfNull(description);
        var match = DescriptionPattern().Match(description);
        if (!match.Success)
        {
            return null;
        }

        static int Int(Group group) => int.Parse(group.Value, CultureInfo.InvariantCulture);
        return new GeneratedDescription(
            match.Groups["template"].Value, Int(match.Groups["size"]), ulong.Parse(match.Groups["seed"].Value, CultureInfo.InvariantCulture),
            match.Groups["attempt"].Success ? Int(match.Groups["attempt"]) : 0, Int(match.Groups["version"]));
    }

    /// <summary>
    /// The zones of <paramref name="state"/>'s map from its description, laid out with the template of that name among
    /// <paramref name="templates"/> (checked against <paramref name="content"/>); a note says when another generator version may have laid
    /// them otherwise.
    /// </summary>
    public static ZoneReading Read(GameState state, IEnumerable<MapTemplate> templates, ContentCatalogs? content = null)
    {
        ArgumentNullException.ThrowIfNull(state);
        ArgumentNullException.ThrowIfNull(templates);
        if (Parse(state.Map.Description) is not { } made)
        {
            return new ZoneReading(null, "Not a generated map (its description does not say how it was generated): the start zones.");
        }

        if (templates.FirstOrDefault(t => t.Name == made.Template) is not { } template)
        {
            return new ZoneReading(null, $"The template \"{made.Template}\" is not found: the start zones.");
        }

        if (state.Map.Width != made.Size || state.Map.Height != made.Size || state.Map.Levels != template.Levels)
        {
            return new ZoneReading(null, "The map's size changed since it was generated: the start zones.");
        }

        ZoneLayout layout;
        try
        {
            layout = ZoneLayouter.Layout(template, made.Size, MapGenerator.AttemptSeed(made.Seed, made.Attempt), content: content);
        }
        catch (ArgumentException e)
        {
            return new ZoneReading(null, $"The template \"{made.Template}\" cannot lay out the zones ({e.Message}): the start zones.");
        }

        var names = layout.ZoneIds.Select(id => template.Zones.First(z => z.Id == id)).Select(Name).ToList();
        var source = $"The zones of \"{made.Template}\" at {made.Size}×{made.Size}, seed {made.Seed}" + (made.Attempt == 0 ? "." : $", attempt {made.Attempt}.");
        var note = made.Version == MapGenerator.Version
            ? source
            : $"{source} Generated by generator version {made.Version}, this is version {MapGenerator.Version}: the zones may lie otherwise.";
        return new ZoneReading(new ZoneMap(names, tile => layout.ZoneAt(tile.X, tile.Y, tile.Level), source), note);
    }

    /// <summary>A zone's name in the legend: its id, its type, and whose start it is.</summary>
    private static string Name(TemplateZone zone) => zone.Type switch
    {
        ZoneType.PlayerStart or ZoneType.AiStart when zone.Owner is { } slot => $"{zone.Id} ({(zone.Type == ZoneType.AiStart ? "computer " : "")}start of slot {slot + 1})",
        _ => $"{zone.Id} ({zone.Type.ToString().ToLowerInvariant()})",
    };

    [GeneratedRegex("""^Generated from the template "(?<template>.*)" at (?<size>\d+)×\d+, seed (?<seed>\d+)(?: \(attempt (?<attempt>\d+)\))?, generator version (?<version>\d+)\.""")]
    private static partial Regex DescriptionPattern();
}
